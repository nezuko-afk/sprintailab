#!/usr/bin/env node
// Classify REA MCP tools into governance risk tiers from REA's own effect flags.
//
// Usage:
//   node scripts/generate-tool-tiers.mjs <path/to/mcp-tool-catalog.json> <rea-commit>
//
// The catalog comes from building upstream/rea and running
// `node scripts/generate-mcp-tool-catalog.mjs` (writes .cache/mcp-tool-catalog.json).
// Rules are deterministic. Anything missing from the output must be DENIED by the proxy.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const [catalogPath, reaCommit = "unknown", reaVersion = "unknown"] = process.argv.slice(2);
if (!catalogPath) {
  console.error("usage: generate-tool-tiers.mjs <catalog.json> [rea-commit] [rea-version]");
  process.exit(2);
}
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { catalog } = JSON.parse(readFileSync(catalogPath, "utf8"));

const TIERS = {
  0: { name: "Read-only", rule: "No spawned engines, no file writes, no network, no mutation" },
  1: { name: "Local analysis", rule: "Spawns analysis engines or writes to REA's private workspace; no network, no target execution" },
  2: { name: "Live system", rule: "Touches the network, a live UI, or alters the target or its analysis state" },
  3: { name: "Executes or modifies", rule: "Runs foreign code or debuggers, instruments a process, or changes a device" },
};

// Judgement calls that override the flag-derived tier. Keep this list short and justified.
const OVERRIDES = {
  annotate_native_function: [1, "Edits the analysis database, not the analyzed software"],
  set_address_name: [1, "Edits the analysis database, not the analyzed software"],
  set_addresses_names: [1, "Edits the analysis database, not the analyzed software"],
  set_bookmark: [1, "Edits the analysis database, not the analyzed software"],
  unset_bookmark: [1, "Edits the analysis database, not the analyzed software"],
  set_comment: [1, "Edits the analysis database, not the analyzed software"],
  set_inline_comment: [1, "Edits the analysis database, not the analyzed software"],
  start_frida_session: [3, "Attaches to or spawns a live process"],
  unload_frida_script: [3, "Part of live process instrumentation"],
  close_frida_session: [3, "Part of live process instrumentation"],
};

const flagTier = (e) => {
  if (e.executesForeignCode || e.mutatesDevice) return 3;
  if (e.accessesNetwork || e.mutatesTarget || e.changesUiState) return 2;
  if (e.launchesProcess || e.writesFilesystem || e.mayDiscardData) return 1;
  return 0;
};

const tools = catalog
  .map((t) => {
    const derived = flagTier(t.effects);
    const o = OVERRIDES[t.name];
    return {
      name: t.name,
      kind: t.kind,
      tier: o ? o[0] : derived,
      derivedTier: derived,
      override: o ? o[1] : null,
      requiresSession: t.requiresSession,
      effects: Object.keys(t.effects).filter((k) => t.effects[k] === true && k !== "idempotent" && k !== "mutatesSession").sort(),
    };
  })
  .sort((a, b) => (a.name < b.name ? -1 : 1));

for (const name of Object.keys(OVERRIDES))
  if (!tools.some((t) => t.name === name)) console.warn(`WARN: override for unknown tool ${name}`);

const counts = { 0: 0, 1: 0, 2: 0, 3: 0 };
tools.forEach((t) => counts[t.tier]++);

const out = {
  generatedFrom: { project: "morluto/rea", version: reaVersion, commit: reaCommit, toolCount: tools.length },
  failClosed: "Any tool name not listed here must be denied.",
  tiers: TIERS,
  counts,
  tools,
};
mkdirSync(join(root, "policy"), { recursive: true });
writeFileSync(join(root, "policy/tool-tiers.json"), JSON.stringify(out, null, 2) + "\n");

// Human-readable summary
const byTier = (n) => tools.filter((t) => t.tier === n);
const list = (n) => byTier(n).map((t) => `\`${t.name}\``).join(", ");
const kinds = {};
for (const t of tools) { kinds[t.kind] ??= [0, 0, 0, 0]; kinds[t.kind][t.tier]++; }
const kindRows = Object.entries(kinds).sort().map(([k, v]) => `| ${k} | ${v.join(" | ")} |`).join("\n");
const ovRows = tools.filter((t) => t.override).map((t) => `| \`${t.name}\` | ${t.derivedTier} | ${t.tier} | ${t.override} |`).join("\n");

const md = `# Tool risk tiers

Generated by \`scripts/generate-tool-tiers.mjs\`. **Do not edit by hand.**

Source: REA \`${reaVersion}\`, commit \`${reaCommit}\`, ${tools.length} tools, taken from REA's own
effect flags in its generated MCP tool catalog. Machine-readable copy: \`policy/tool-tiers.json\`.

## Tiers

| Tier | Name | Rule | Tools |
| --- | --- | --- | --- |
${[0, 1, 2, 3].map((n) => `| ${n} | ${TIERS[n].name} | ${TIERS[n].rule} | ${counts[n]} |`).join("\n")}

**Fail closed:** a tool that is not in \`policy/tool-tiers.json\` is denied. When upstream
REA is updated, regenerate this file and review the diff before allowing new tools.

## Proposed handling

| Tier | Authorization declaration | Sandbox | Minimum role |
| --- | --- | --- | --- |
| 0 | Once per session | No | Viewer |
| 1 | Per target | No | Analyst |
| 2 | Per target, with reference id | Recommended | Analyst |
| 3 | Per target, with reference id and second approval | Required | Senior analyst |

This is a proposal for review, not a final policy.

## Tier 3: executes or modifies (${counts[3]})

${list(3)}

## Tier 2: live system (${counts[2]})

${list(2)}

## Tier counts by tool kind

| Kind | T0 | T1 | T2 | T3 |
| --- | --- | --- | --- | --- |
${kindRows}

## Overrides to the flag-derived tier

| Tool | Derived | Final | Reason |
| --- | --- | --- | --- |
${ovRows}

## Known conservative choices

- \`close_gdb_session\` and \`close_rizin_debug_session\` are Tier 3 because REA flags them as
  able to execute code. Closing a session you opened is harmless; treat as same-role in the proxy.
- Tier 0/1 tools still read the target files. They are not "safe" on unauthorized targets,
  which is why the authorization declaration applies to every tier.

## Regenerating

\`\`\`bash
# 1. In a scratch copy of upstream/rea (keep the submodule clean):
npm ci --ignore-scripts && npx tsc -p tsconfig.build.json
node scripts/generate-mcp-tool-catalog.mjs        # writes .cache/mcp-tool-catalog.json
# 2. From this repo:
node scripts/generate-tool-tiers.mjs <catalog.json> <rea-commit> <rea-version>
\`\`\`
`;
writeFileSync(join(root, "docs/governance/tool-tiers.md"), md);
console.log("tiers:", counts, "tools:", tools.length);
